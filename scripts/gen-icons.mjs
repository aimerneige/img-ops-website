// Regenerates src/lib/icons.ts from the list below (run: node scripts-gen-icons.mjs).
import { writeFileSync, existsSync } from 'node:fs';
const names = `add add_photo_alternate arrow_back arrow_forward auto_awesome_mosaic brightness_auto check close content_copy dark_mode delete delete_sweep download drag_indicator flip format_bold gradient grid_view help image keyboard_alt language light_mode menu more_vert north_east palette photo_library rectangle circle rotate_right shuffle splitscreen_right splitscreen_bottom splitscreen_add swap_horiz swap_vert text_fields undo redo upload zoom_in zoom_out fit_screen view_agenda view_column water_drop branding_watermark aspect_ratio colorize restart_alt arrow_drop_down drag_pan view_quilt remove arrow_upward arrow_downward folder_zip grid_on layers arrow_selector_tool crop blur_on cancel rounded_corner padding opacity format_size edit check_circle info tile_small dashboard_customize tune`.split(/\s+/);
let out = '// Generated by scripts-gen-icons.mjs — Material Symbols Rounded (Apache-2.0)\n';
const ids = [];
for (const n of names) {
  const p = `@material-symbols/svg-400/rounded/${n}.svg`;
  if (!existsSync('node_modules/' + p)) { console.error('missing', n); continue; }
  const id = 'i_' + n;
  ids.push([n, id]);
  out += `import ${id} from '${p}?raw';\n`;
}
out += '\nexport const icons = {\n' + ids.map(([n, id]) => `  ${n}: ${id},`).join('\n') + '\n} as const;\n\nexport type IconName = keyof typeof icons;\n';
writeFileSync('src/lib/icons.ts', out);
console.log(ids.length, 'icons');
